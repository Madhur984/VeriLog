/* ═══════════════════════ machine 2: A-B, DA=AX+BX, DB=A'X, Y=(A+B)X' ═══════════════════════
   The deck's classic worked example - reused verbatim as the S06 detective case file. */
interface ABRow { A: number; B: number; X: number; DA: number; DB: number; nextA: number; nextB: number; Y: number }
const abRows = (): ABRow[] => {
  const out: ABRow[] = [];
  for (const A of [0, 1]) for (const B of [0, 1]) for (const X of [0, 1]) {
    const DA = (A & X) | (B & X);
    const DB = (A ^ 1) & X;
    const nextA = ffNext('D', A, DA);
    const nextB = ffNext('D', B, DB);
    const Y = (A | B) & (X ^ 1);
    out.push({ A, B, X, DA, DB, nextA, nextB, Y });
  }
  return out;
};
const abStates = fourStates();
const abEdges: FSMEdge[] = abRows().map((r) => {
  const from = `S${r.A}${r.B}`, to = `S${r.nextA}${r.nextB}`;
  return { from, to, label: `${r.X}/${r.Y}`, curve: curveFor(from, to) };
});

