/* ═══════════════════════ machine 3: JK practice, JA=B, KA=B.X', JB=X, KB=A, Y=A.B ═══════════════════════ */
interface JKRow { A: number; B: number; X: number; JA: number; KA: number; JB: number; KB: number; nextA: number; nextB: number; Y: number }
const jkRows = (): JKRow[] => {
  const out: JKRow[] = [];
  for (const A of [0, 1]) for (const B of [0, 1]) for (const X of [0, 1]) {
    const JA = B, KA = B & (X ^ 1);
    const JB = X, KB = A;
    const nextA = ffNext('JK', A, JA, KA);
    const nextB = ffNext('JK', B, JB, KB);
    const Y = A & B;
    out.push({ A, B, X, JA, KA, JB, KB, nextA, nextB, Y });
  }
  return out;
};
const jkAllRows = jkRows();
const jkOutOf = (a: number, b: number) => a & b;
const jkStates: FSMState[] = fourStates().map((s) => {
  const a = Number(s.label[0]), b = Number(s.label[1]);
  return { ...s, label: `${s.label} (Y=${jkOutOf(a, b)})` };
});
const jkEdges: FSMEdge[] = jkAllRows.map((r) => {
  const from = `S${r.A}${r.B}`, to = `S${r.nextA}${r.nextB}`;
  return { from, to, label: `X=${r.X}`, curve: curveFor(from, to) };
});

